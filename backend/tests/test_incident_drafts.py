def test_simulated_settings_path_opens_no_external_ai_sockets(
    registry_client: TestClient,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    runner = ScriptedRunner([_observation(), _observation()])
    _install_runner(registry_client, runner)
    monkeypatch.setenv("ANALYSIS_PROVIDER", "simulated")
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    get_settings.cache_clear()
    for attr in ("incident_draft_provider", "resolved_incident_draft_provider"):
        if hasattr(registry_client.app.state, attr):
            delattr(registry_client.app.state, attr)

    original_connect = socket.create_connection
    blocked: list[str] = []

    def guarded_connect(address, *args, **kwargs):  # type: ignore[no-untyped-def]
        host = address[0] if isinstance(address, tuple) else str(address)
        if host in {"127.0.0.1", "localhost", "::1"}:
            return original_connect(address, *args, **kwargs)
        blocked.append(str(host))
        raise AssertionError(f"external network forbidden during simulated draft: {host}")

    monkeypatch.setattr(socket, "create_connection", guarded_connect)
    monkeypatch.setattr(
        "app.services.incident_drafts.OpenAIIncidentDraftProvider.draft",
        lambda *_a, **_k: (_ for _ in ()).throw(AssertionError("OpenAI must not run")),
    )

    website_id = _create_website(registry_client)
    try:
        _run_check(registry_client, website_id)
        _run_check(registry_client, website_id)
        response = registry_client.post(f"/api/websites/{website_id}/incident-drafts")
        assert response.status_code == 201, response.text
        body = response.json()
        assert body["provider"] == "simulated"
        assert body["model_name"] == SIMULATED_MODEL_NAME
        assert "SIMULATED" in body["limitations"]
        assert blocked == []
    finally:
        registry_client.delete(f"/api/websites/{website_id}")
        get_settings.cache_clear()


