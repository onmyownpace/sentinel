def test_create_list_reuse_incident_draft(registry_client: TestClient) -> None:
    runner = ScriptedRunner([_observation(), _observation(http_status=502)])
    provider = ScriptedIncidentProvider([_draft(), _draft(paragraph="Should not run")])
    _install_runner(registry_client, runner)
    _install_provider(registry_client, provider)
    website_id = _create_website(registry_client)
    try:
        first_check = _run_check(registry_client, website_id)
        second_check = _run_check(registry_client, website_id)
        assert first_check["outcome"] == "failed"

        created = registry_client.post(
            f"/api/websites/{website_id}/incident-drafts",
            params={"limit": 5},
        )
        assert created.status_code == 201, created.text
        body = created.json()
        assert body["website_id"] == website_id
        assert body["provider"] == "simulated"
        assert body["failed_check_count"] == 2
        assert body["text"].startswith("[Sentinel]")
        assert "paragraph" in body
        assert set(body["check_ids"]) == {first_check["id"], second_check["id"]}
        assert len(provider.calls) == 1
        assert provider.calls[0]["failed_check_count"] == 2

        reused = registry_client.post(f"/api/websites/{website_id}/incident-drafts")
        assert reused.status_code == 200
        assert reused.json()["id"] == body["id"]
        assert len(provider.calls) == 1

        listed = registry_client.get(f"/api/websites/{website_id}/incident-drafts")
        assert listed.status_code == 200
        assert any(item["id"] == body["id"] for item in listed.json())

        fetched = registry_client.get(f"/api/incident-drafts/{body['id']}")
        assert fetched.status_code == 200
        assert fetched.json()["paragraph"] == body["paragraph"]
    finally:
        registry_client.delete(f"/api/websites/{website_id}")


