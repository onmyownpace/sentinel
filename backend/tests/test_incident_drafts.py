class ScriptedRunner:
    def __init__(self, observations: list[CheckObservation]) -> None:
        self.observations = list(observations)

    async def run(self, url: str) -> CheckObservation:
        if not self.observations:
            raise AssertionError("runner called more times than scripted")
        return self.observations.pop(0)


class ScriptedIncidentProvider:
    def __init__(self, results: list[IncidentDraftResult] | None = None) -> None:
        self.results = list(results or [])
        self.calls: list[dict[str, object]] = []

    async def draft(self, evidence: dict[str, object]) -> IncidentDraftResult:
        self.calls.append(evidence)
        if not self.results:
            raise AssertionError("incident provider called more times than scripted")
        return self.results.pop(0)


def _observation(**overrides) -> CheckObservation:
    values: dict = {
        "outcome": "failed",
        "http_status": 503,
        "page_title": "Unavailable",
        "final_url": "http://8.8.8.8/down",
        "duration_ms": 220,
        "console_errors": (),
        "failed_requests": (),
        "error_message": "The page responded with HTTP 503.",
    }
    values.update(overrides)
    return CheckObservation(**values)


def _draft(**overrides) -> IncidentDraftResult:
    values: dict = {
        "paragraph": "Simulated incident draft covering recent failures.",
        "text": "[Sentinel] Incident draft · Site: 2 recent failure(s)",
        "severity": "high",
        "observations": ["Draft covers the newest 2 failed check(s)."],
        "limitations": "SIMULATED INCIDENT DRAFT — not generated by a live AI model.",
    }
    values.update(overrides)
    return IncidentDraftResult(**values)


def _install_runner(client: TestClient, runner: ScriptedRunner) -> None:
    client.app.state.check_runner = runner


def _install_provider(client: TestClient, provider: ScriptedIncidentProvider) -> None:
    client.app.state.incident_draft_provider = provider
    client.app.state.incident_draft_model_name = "test-model"
    client.app.state.incident_draft_provider_name = "simulated"


def _create_website(client: TestClient) -> str:
    created = client.post(
        "/api/websites",
        json={"name": "Incident site", "base_url": f"http://8.8.8.8/{uuid4().hex}"},
    )
    assert created.status_code == 201, created.text
    return created.json()["id"]


def _run_check(client: TestClient, website_id: str) -> dict:
    response = client.post(
        f"/api/websites/{website_id}/checks",
        json={"authorized": True},
    )
    assert response.status_code == 201, response.text
    return response.json()


