class ScriptedRunner:
    def __init__(self, observations: list[CheckObservation]) -> None:
        self.observations = list(observations)
        self.calls: list[str] = []

    async def run(self, url: str) -> CheckObservation:
        self.calls.append(url)
        if not self.observations:
            raise AssertionError("runner called more times than scripted")
        return self.observations.pop(0)


class ScriptedPatternProvider:
    def __init__(
        self,
        results: list[PatternHintsResult] | None = None,
        *,
        error: Exception | None = None,
    ) -> None:
        self.results = list(results or [])
        self.error = error
        self.calls: list[dict[str, object]] = []

    async def analyze(self, evidence: dict[str, object]) -> PatternHintsResult:
        self.calls.append(evidence)
        if self.error is not None:
            raise self.error
        if not self.results:
            raise AssertionError("pattern provider called more times than scripted")
        return self.results.pop(0)


def _observation(**overrides) -> CheckObservation:
    values: dict = {
        "outcome": "failed",
        "http_status": 503,
        "page_title": "Unavailable",
        "final_url": "http://8.8.8.8/down",
        "duration_ms": 220,
        "console_errors": (),
        "failed_requests": (),
        "error_message": "The page responded with HTTP 503.",
    }
    values.update(overrides)
    return CheckObservation(**values)


def _hint(**overrides) -> PatternHintsResult:
    values: dict = {
        "summary": "Simulated pattern hints over recent checks. 2/3 failed.",
        "severity": "high",
        "patterns": [
            PatternHintItem(
                kind="repeated_failure",
                title="Repeated failures in the sample",
                detail="2 of 3 checks failed.",
                confidence="medium",
                evidence="failure_count=2",
            )
        ],
        "confirmed_observations": ["Sampled 3 check(s).", "Failures: 2; successes: 1."],
        "recommended_investigation_steps": [
            "Compare the newest failed checks.",
            "Treat this as a local heuristic only.",
        ],
        "limitations": "SIMULATED PATTERN HINTS — not generated by a live AI model.",
    }
    values.update(overrides)
    return PatternHintsResult(**values)


def _install_runner(client: TestClient, runner: ScriptedRunner) -> None:
    client.app.state.check_runner = runner


def _install_provider(client: TestClient, provider: ScriptedPatternProvider) -> None:
    client.app.state.pattern_hint_provider = provider
    client.app.state.pattern_hint_model_name = "test-model"
    client.app.state.pattern_hint_provider_name = "simulated"


def _create_website(client: TestClient) -> str:
    created = client.post(
        "/api/websites",
        json={"name": "Pattern site", "base_url": f"http://8.8.8.8/{uuid4().hex}"},
    )
    assert created.status_code == 201, created.text
    return created.json()["id"]


def _run_check(client: TestClient, website_id: str) -> dict:
    response = client.post(
        f"/api/websites/{website_id}/checks",
        json={"authorized": True},
    )
    assert response.status_code == 201, response.text
    return response.json()


def test_simulated_builder_flags_repeated_failures_and_spikes() -> None:
    evidence = {
        "window": "7d",
        "sample_limit": 50,
        "check_count": 4,
        "failure_count": 3,
        "success_count": 1,
        "avg_duration_ms": 400.0,
        "p95_duration_ms": 1800,
        "latest_check_id": str(uuid4()),
        "checks": [
            {"id": "a", "outcome": "failed", "http_status": 503, "duration_ms": 1800, "error_message": "x"},
            {"id": "b", "outcome": "failed", "http_status": 503, "duration_ms": 180, "error_message": "x"},
            {"id": "c", "outcome": "failed", "http_status": 503, "duration_ms": 170, "error_message": "x"},
            {"id": "d", "outcome": "success", "http_status": 200, "duration_ms": 150, "error_message": None},
        ],
    }
    result = build_simulated_pattern_hints(evidence)
    kinds = {item.kind for item in result.patterns}
    assert "repeated_failure" in kinds
    assert "status_cluster" in kinds
    assert "failure_streak" in kinds
    assert "latency_spike" in kinds
    assert result.summary.lower().startswith("simulated")
    assert "SIMULATED" in result.limitations


def test_create_pattern_hints_reuses_row(registry_client: TestClient) -> None:
    runner = ScriptedRunner(
        [
            _observation(),
            _observation(http_status=502, duration_ms=240),
            _observation(
                outcome="success",
                http_status=200,
                page_title="Ok",
                error_message=None,
                duration_ms=120,
            ),
        ]
    )
    provider = ScriptedPatternProvider([_hint(), _hint()])
    _install_runner(registry_client, runner)
    _install_provider(registry_client, provider)
    website_id = _create_website(registry_client)
    try:
        _run_check(registry_client, website_id)
        _run_check(registry_client, website_id)
        _run_check(registry_client, website_id)

        first = registry_client.post(f"/api/websites/{website_id}/pattern-hints")
        assert first.status_code == 201, first.text
        body = first.json()
        assert body["website_id"] == website_id
        assert body["provider"] == "simulated"
        assert body["check_count"] == 3
        assert body["failure_count"] == 2
        assert body["patterns"]
        assert len(provider.calls) == 1

        second = registry_client.post(f"/api/websites/{website_id}/pattern-hints")
        assert second.status_code == 200, second.text
        assert second.json()["id"] == body["id"]
        assert len(provider.calls) == 1

        fetched = registry_client.get(f"/api/websites/{website_id}/pattern-hints")
        assert fetched.status_code == 200
        assert fetched.json()["id"] == body["id"]
    finally:
        registry_client.delete(f"/api/websites/{website_id}")


