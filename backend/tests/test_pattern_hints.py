def test_refresh_forces_new_provider_call(registry_client: TestClient) -> None:
    runner = ScriptedRunner([_observation(), _observation()])
    provider = ScriptedPatternProvider([_hint(), _hint(summary="Refreshed hints.")])
    _install_runner(registry_client, runner)
    _install_provider(registry_client, provider)
    website_id = _create_website(registry_client)
    try:
        _run_check(registry_client, website_id)
        first = registry_client.post(f"/api/websites/{website_id}/pattern-hints")
        assert first.status_code == 201
        refreshed = registry_client.post(
            f"/api/websites/{website_id}/pattern-hints",
            params={"refresh": "true"},
        )
        assert refreshed.status_code == 201, refreshed.text
        assert refreshed.json()["summary"] == "Refreshed hints."
        assert len(provider.calls) == 2
    finally:
        registry_client.delete(f"/api/websites/{website_id}")
