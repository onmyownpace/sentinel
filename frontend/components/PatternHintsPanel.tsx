"use client";

import { useState } from "react";

import {
  createPatternHints,
  getPatternHints,
  type PatternHints,
} from "@/lib/patternHints";
import { WebsiteApiError } from "@/lib/websites";

type PatternHintsPanelProps = {
  websiteId: string;
  disabled?: boolean;
};

export function PatternHintsPanel({ websiteId, disabled = false }: PatternHintsPanelProps) {
  const [hints, setHints] = useState<PatternHints | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [lookedUp, setLookedUp] = useState(false);

  async function onGenerate(refresh = false) {
    setLoading(true);
    setError(null);
    try {
      const result = await createPatternHints(websiteId, { window: "7d", refresh });
      setHints(result);
      setLookedUp(true);
    } catch (caught) {
      setError(
        caught instanceof WebsiteApiError
          ? caught.message
          : "Pattern hints could not be generated.",
      );
    } finally {
      setLoading(false);
    }
  }

  async function onLoadExisting() {
    setLoading(true);
    setError(null);
    try {
      const existing = await getPatternHints(websiteId);
      setHints(existing);
      setLookedUp(true);
    } catch (caught) {
      setError(
        caught instanceof WebsiteApiError
          ? caught.message
          : "Stored pattern hints could not be loaded.",
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="failure-analysis pattern-hints" aria-busy={loading}>
      <h3>Historical pattern hints</h3>
      <p className="hint tight">
        On-demand summary of repeated failures and latency spikes across recent checks for this
        site (AI-2). Default provider is simulated — no paid AI calls. Optional{" "}
        <code>ANALYSIS_PROVIDER=openai</code> reuses the same switch as single-check analysis.
      </p>
      <div className="actions">
        <button type="button" disabled={disabled || loading} onClick={() => void onGenerate(false)}>
          {loading && !hints ? "Summarizing…" : "Summarize patterns"}
        </button>
        <button type="button" disabled={disabled || loading} onClick={() => void onLoadExisting()}>
          {loading ? "Loading…" : "Show saved hints"}
        </button>
        <button type="button" disabled={disabled || loading} onClick={() => void onGenerate(true)}>
          Refresh
        </button>
      </div>
      {error ? (
        <p className="banner bad" role="alert">
          {error}
        </p>
      ) : null}
      {lookedUp && !hints && !error ? (
        <p className="hint tight">No saved pattern hints for this site yet.</p>
      ) : null}
      {hints ? <HintsResult hints={hints} /> : null}
    </div>
  );
}

function HintsResult({ hints }: { hints: PatternHints }) {
  const simulated = hints.provider === "simulated";

  return (
    <div className="analysis-result">
      {simulated ? (
        <p className="banner warn" role="status">
          Simulated pattern hints — local heuristics only. This is not output from a live AI model.
        </p>
      ) : (
        <p className="banner ok" role="status">
          OpenAI pattern hints — generated by a live model call.
        </p>
      )}
      <p className="meta">
        Provider: {hints.provider} · Severity: {hints.severity} · Model: {hints.model_name} · Window:{" "}
        {hints.window} · Sample: {hints.check_count} checks ({hints.failure_count} failed) ·{" "}
        {formatTimestamp(hints.created_at)}
      </p>
      <p>{hints.summary}</p>
      <section>
        <p className="meta">Patterns</p>
        <ul>
          {hints.patterns.map((item, index) => (
            <li key={`${index}:${item.kind}:${item.title}`}>
              <strong>{item.title}</strong> · {item.kind} · confidence {item.confidence}
              <br />
              {item.detail}
              <br />
              <span className="meta">Evidence: {item.evidence}</span>
            </li>
          ))}
        </ul>
      </section>
      <section>
        <p className="meta">Confirmed observations</p>
        <ul>
          {hints.confirmed_observations.map((item, index) => (
            <li key={`${index}:${item}`}>{item}</li>
          ))}
        </ul>
      </section>
      <section>
        <p className="meta">Recommended investigation steps</p>
        <ol>
          {hints.recommended_investigation_steps.map((item, index) => (
            <li key={`${index}:${item}`}>{item}</li>
          ))}
        </ol>
      </section>
      <p className="meta">Limitations: {hints.limitations}</p>
    </div>
  );
}

function formatTimestamp(value: string): string {
  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) {
    return value;
  }
  return parsed.toLocaleString();
}
