"use client";

import { useState } from "react";

import {
  createIncidentDraft,
  listIncidentDrafts,
  type IncidentDraft,
} from "@/lib/incidentDrafts";
import { WebsiteApiError } from "@/lib/websites";

type IncidentDraftPanelProps = {
  websiteId: string;
  disabled?: boolean;
};

export function IncidentDraftPanel({ websiteId, disabled = false }: IncidentDraftPanelProps) {
  const [draft, setDraft] = useState<IncidentDraft | null>(null);
  const [history, setHistory] = useState<IncidentDraft[] | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function onDraft(refresh = false) {
    setLoading(true);
    setError(null);
    try {
      const result = await createIncidentDraft(websiteId, { limit: 5, refresh });
      setDraft(result);
      setHistory(await listIncidentDrafts(websiteId));
    } catch (caught) {
      setError(
        caught instanceof WebsiteApiError
          ? caught.message
          : "Incident draft could not be generated.",
      );
    } finally {
      setLoading(false);
    }
  }

  async function onLoadHistory() {
    setLoading(true);
    setError(null);
    try {
      const rows = await listIncidentDrafts(websiteId);
      setHistory(rows);
      setDraft(rows[0] ?? null);
    } catch (caught) {
      setError(
        caught instanceof WebsiteApiError
          ? caught.message
          : "Incident drafts could not be loaded.",
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="failure-analysis incident-draft" aria-busy={loading}>
      <h3>Incident summary draft</h3>
      <p className="hint tight">
        One-click paragraph from the newest failed checks (+ any saved analyses). Webhook-friendly
        JSON (<code>text</code> + <code>paragraph</code>) for n8n. Default provider is simulated —
        no paid AI.
      </p>
      <div className="actions">
        <button type="button" disabled={disabled || loading} onClick={() => void onDraft(false)}>
          {loading && !draft ? "Drafting…" : "Draft incident"}
        </button>
        <button type="button" disabled={disabled || loading} onClick={() => void onLoadHistory()}>
          {loading ? "Loading…" : "Show saved drafts"}
        </button>
        <button type="button" disabled={disabled || loading} onClick={() => void onDraft(true)}>
          Refresh
        </button>
      </div>
      {error ? (
        <p className="banner bad" role="alert">
          {error}
        </p>
      ) : null}
      {history && history.length === 0 && !error ? (
        <p className="hint tight">No incident drafts yet. Need at least one failed check.</p>
      ) : null}
      {draft ? <DraftResult draft={draft} /> : null}
      {history && history.length > 1 ? (
        <p className="meta">{history.length} drafts stored for this site (newest first).</p>
      ) : null}
    </div>
  );
}

function DraftResult({ draft }: { draft: IncidentDraft }) {
  const simulated = draft.provider === "simulated";

  return (
    <div className="analysis-result">
      {simulated ? (
        <p className="banner warn" role="status">
          Simulated incident draft — local heuristics only. This is not output from a live AI model.
        </p>
      ) : (
        <p className="banner ok" role="status">
          OpenAI incident draft — generated by a live model call.
        </p>
      )}
      <p className="meta">
        Provider: {draft.provider} · Severity: {draft.severity} · Model: {draft.model_name} ·{" "}
        {draft.failed_check_count} failed check(s) · {formatTimestamp(draft.created_at)}
      </p>
      <p>
        <strong>Webhook text:</strong> {draft.text}
      </p>
      <p>{draft.paragraph}</p>
      <section>
        <p className="meta">Observations</p>
        <ul>
          {draft.observations.map((item, index) => (
            <li key={`${index}:${item}`}>{item}</li>
          ))}
        </ul>
      </section>
      <p className="meta">Limitations: {draft.limitations}</p>
    </div>
  );
}

function formatTimestamp(value: string): string {
  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) {
    return value;
  }
  return parsed.toLocaleString();
}
