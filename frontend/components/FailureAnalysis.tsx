"use client";

import { useState } from "react";

import {
  createCheckAnalysis,
  getCheckAnalysis,
  type FailureAnalysis as Analysis,
} from "@/lib/analysis";
import { WebsiteApiError } from "@/lib/websites";

type FailureAnalysisPanelProps = {
  checkId: string;
  disabled?: boolean;
};

export function FailureAnalysisPanel({ checkId, disabled = false }: FailureAnalysisPanelProps) {
  const [analysis, setAnalysis] = useState<Analysis | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [lookedUp, setLookedUp] = useState(false);

  async function onAnalyze() {
    setLoading(true);
    setError(null);
    try {
      const result = await createCheckAnalysis(checkId);
      setAnalysis(result);
      setLookedUp(true);
    } catch (caught) {
      setError(
        caught instanceof WebsiteApiError
          ? caught.message
          : "The failure analysis could not be started.",
      );
    } finally {
      setLoading(false);
    }
  }

  async function onLoadExisting() {
    setLoading(true);
    setError(null);
    try {
      const existing = await getCheckAnalysis(checkId);
      setAnalysis(existing);
      setLookedUp(true);
      if (existing === null) {
        setError(null);
      }
    } catch (caught) {
      setError(
        caught instanceof WebsiteApiError
          ? caught.message
          : "The stored analysis could not be loaded.",
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="failure-analysis" aria-busy={loading}>
      <div className="actions">
        <button type="button" disabled={disabled || loading} onClick={() => void onAnalyze()}>
          {loading && !analysis ? "Analyzing…" : "Analyze failure"}
        </button>
        <button type="button" disabled={disabled || loading} onClick={() => void onLoadExisting()}>
          {loading ? "Loading…" : "Show saved analysis"}
        </button>
      </div>
      <p className="hint tight">
        Analysis uses the saved check result.
      </p>
      {error ? (
        <p className="banner bad" role="alert">
          {error}
        </p>
      ) : null}
      {lookedUp && !analysis && !error ? (
        <p className="hint tight">No saved analysis for this check yet.</p>
      ) : null}
      {analysis ? <AnalysisResult analysis={analysis} /> : null}
    </div>
  );
}

function AnalysisResult({ analysis }: { analysis: Analysis }) {
  const simulated = analysis.provider === "simulated";

  return (
    <div className="analysis-result">
      {simulated ? (
        <p className="banner warn" role="status">
          Simulated analysis — local heuristics only. This is not output from a live AI model.
        </p>
      ) : (
        <p className="banner ok" role="status">
          OpenAI analysis — generated by a live model call.
        </p>
      )}
      <p className="meta">
        Provider: {analysis.provider} · Severity: {analysis.severity} · Model: {analysis.model_name}{" "}
        · {formatTimestamp(analysis.created_at)}
      </p>
      <p>{analysis.summary}</p>
      <section>
        <p className="meta">Confirmed observations</p>
        <ul>
          {analysis.confirmed_observations.map((item, index) => (
            <li key={`${index}:${item}`}>{item}</li>
          ))}
        </ul>
      </section>
      <section>
        <p className="meta">Possible causes (hypotheses)</p>
        <ul>
          {analysis.possible_causes.map((item, index) => (
            <li key={`${index}:${item.cause}`}>
              {item.cause} · confidence {item.confidence}
              <br />
              <span className="meta">Evidence: {item.evidence}</span>
            </li>
          ))}
        </ul>
      </section>
      <section>
        <p className="meta">Recommended investigation steps</p>
        <ol>
          {analysis.recommended_investigation_steps.map((item, index) => (
            <li key={`${index}:${item}`}>{item}</li>
          ))}
        </ol>
      </section>
      <p className="meta">Limitations: {analysis.limitations}</p>
    </div>
  );
}

function formatTimestamp(value: string): string {
  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) {
    return value;
  }
  return parsed.toLocaleString();
}
